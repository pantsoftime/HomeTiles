#!/usr/bin/env node
// FORK: generates the battery charge indicator font of the Settings tile:
//   src/fonts/fork_battery_icons_22.c
// The Tab5's Settings tile shows its battery percentage in the 24 px folder
// value font; this indicator sits beside it at about the same height. Only
// the Tab5 measures its battery, so one size is enough. A copy of
// tools/generate-mdi-bar-icon-fonts.mjs (same converter and MDI release, see
// there why the tile's own icon font is not scaled down) with its own icon
// list and font name, so upstream's generator and fonts stay untouched.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync, execSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONVERTER = 'lv_font_conv@1.5.3';
const MDI = '@mdi/font@7.4.47';

// Charging, discharging, idle (on power, no current either way).
export const BAR_ICONS = ['lightning-bolt', 'arrow-down', 'power-plug'];
export const SIZES = [22];

// The codepoints of BAR_ICONS from the firmware's own MDI name table.
export function barIconCodepoints() {
  const table = fs.readFileSync(path.join(root, 'src/tiles/icons/mdi_icons.cpp'), 'utf8');
  const map = new Map([...table.matchAll(/\{"([a-z0-9-]+)", 0x([0-9A-Fa-f]+)\}/g)].map((m) => [m[1], parseInt(m[2], 16)]));
  return BAR_ICONS.map((name) => {
    if (!map.has(name)) throw new Error(`MDI icon not in src/tiles/icons/mdi_icons.cpp: ${name}`);
    return map.get(name);
  }).sort((a, b) => a - b);
}

export const rangeText = (codepoints) => codepoints.map((cp) => `0x${cp.toString(16).toUpperCase()}`).join(',');

function postProcess(source, size, range) {
  const name = `fork_battery_icons_${size}`;
  const replace = (pattern, replacement) => {
    if (!pattern.test(source)) throw new Error(`${name}: pattern not found: ${pattern}`);
    source = source.replace(pattern, replacement);
  };
  replace(/^ \* Opts: .+$/m,
    ` * Opts: --bpp 4 --size ${size} --font materialdesignicons-webfont.woff --range ${range} ` +
    `--format lvgl --lv-font-name ${name}\n` +
    ' * Generated by tools/generate-fork-battery-icon-font.mjs. Do not edit by hand.');
  replace(/^#ifdef LV_LVGL_H_INCLUDE_SIMPLE\r?\n#include "lvgl\.h"\r?\n#else\r?\n#include "lvgl\/lvgl\.h"\r?\n#endif/m,
    '#include "lvgl.h"');
  return source.replace(/\r\n/g, '\n').trimEnd() + '\n';
}

function pack(spec, temp) {
  execSync(`npm pack ${spec} --pack-destination "${temp}"`, {stdio: 'ignore'});
}

function writeFonts() {
  const range = rangeText(barIconCodepoints());
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'HomeTiles-fork-battery-icons-'));
  try {
    for (const spec of [CONVERTER, MDI]) {
      const dir = path.join(temp, spec.replace(/[@/]/g, '_'));
      fs.mkdirSync(dir);
      pack(spec, dir);
      const archive = fs.readdirSync(dir).find((f) => f.endsWith('.tgz'));
      if (!archive) throw new Error(`Unable to download ${spec}`);
      execFileSync('tar', ['-xf', archive, '-C', '.'], {cwd: dir});
    }
    const converter = path.join(temp, CONVERTER.replace(/[@/]/g, '_'), 'package', 'lv_font_conv.js');
    const woff = path.join(temp, MDI.replace(/[@/]/g, '_'), 'package', 'fonts', 'materialdesignicons-webfont.woff');
    for (const size of SIZES) {
      const name = `fork_battery_icons_${size}`;
      const generated = path.join(temp, `${name}.c`);
      execFileSync(process.execPath, [converter, '--bpp', '4', '--size', String(size), '--font', woff,
        '--range', range, '--format', 'lvgl', '--lv-font-name', name, '-o', generated], {stdio: 'inherit'});
      const output = path.join(root, 'src/fonts', `${name}.c`);
      fs.writeFileSync(output, postProcess(fs.readFileSync(generated, 'utf8'), size, range));
      console.log(`Generated ${path.relative(root, output)}`);
    }
  } finally {
    fs.rmSync(temp, {recursive: true, force: true});
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) writeFonts();
